print("Dairenin Alanı : pi * r * r")
print("Dairenin Çevresi : 2 * pi * r")
print("Yarıçapı verilen bir dairenin alanını ve çevresini hesaplayanız (pi=3.14)")
r= input("Yarıçapı giriniz: ")
pi = 3.14
toplamAlan = pi*float(r)**2
toplamCevre = 2*pi*float(r)
print("Dairenin Alanı:", toplamAlan)
print("Dairenin Çevresi:", toplamCevre)
print("Dairenin Alanı:", toplamAlan, "Dairenin Çevresi:", toplamCevre)